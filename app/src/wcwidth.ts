function inRanges(cp: number, ranges: Array<[number, number]>): boolean {
  let lo = 0;
  let hi = ranges.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [a, b] = ranges[mid];
    if (cp < a) hi = mid - 1;
    else if (cp > b) lo = mid + 1;
    else return true;
  }
  return false;
}

export function codepointWidth(cp: number): 0 | 1 | 2 {
  if (cp === 0) return 0;
  if (cp < 0x20 || (cp >= 0x7f && cp < 0xa0)) return 0;
  if (inRanges(cp, ZERO)) return 0;
  if (inRanges(cp, WIDE)) return 2;
  return 1;
}

/** Width of one grapheme cluster: wide if any part is wide or it asks for emoji presentation. */
export function graphemeWidth(g: string): 0 | 1 | 2 {
  let w: 0 | 1 | 2 = 0;
  for (const ch of g) {
    const cp = ch.codePointAt(0)!;
    if (cp === 0xfe0f && w === 1) return 2;
    const cw = codepointWidth(cp);
    if (cw > w) w = cw;
  }
  return w;
}

const segmenter =
  typeof Intl !== "undefined" && "Segmenter" in Intl
    ? new Intl.Segmenter(undefined, { granularity: "grapheme" })
    : null;

export function graphemes(s: string): string[] {
  if (segmenter) return Array.from(segmenter.segment(s), (x) => x.segment);
  return Array.from(s);
}

export function stringWidth(s: string): number {
  let w = 0;
  for (const g of graphemes(s)) w += graphemeWidth(g);
  return w;
}
